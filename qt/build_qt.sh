#!/bin/bash

# =========================================================
# RK3568 Qt 5.15.8 ARM64 编译脚本
#
# 用法：
#   ./build_qt.sh 001
#   ./build_qt.sh 002
#
# 功能：
#   1. 自动加载 RK3568 ARM64 交叉编译环境
#   2. 自动检查 Qt 5.15.8
#   3. 自动清理上一次编译
#   4. 自动执行 qmake
#   5. 自动 make -j12
#   6. 自动检查生成程序
#   7. 自动检查程序是否为 ARM64
#   8. 显示 adb push 命令
# =========================================================

set -e

# =========================================================
# 配置
# =========================================================

SDK_ENV="/opt/atk-dlrk3568-5_10_sdk-toolchain/environment-setup"

PROJECT_ROOT="$HOME/rk3568_qt"

JOBS=12


# =========================================================
# 错误处理
# =========================================================

error_exit()
{
    echo
    echo "========================================"
    echo "                 编译失败"
    echo "========================================"
    echo
    echo "错误位置：$1"
    echo
    exit 1
}


# =========================================================
# 检查参数
# =========================================================

if [ $# -lt 1 ]; then

    echo
    echo "用法："
    echo
    echo "  $0 <项目名>"
    echo
    echo "例如："
    echo "  $0 001"
    echo "  $0 002"
    echo
    exit 1

fi


# =========================================================
# 确定项目目录
# =========================================================

PROJECT="$1"

# 如果不是绝对路径
if [[ "$PROJECT" != /* ]]; then
    PROJECT="$PROJECT_ROOT/$PROJECT"
fi


# =========================================================
# 开始
# =========================================================

echo
echo "========================================"
echo "   RK3568 Qt 5.15.8 ARM64 编译工具"
echo "========================================"


# =========================================================
# [1/7] 加载 SDK 环境
# =========================================================

echo
echo "========================================"
echo "[1/7] 加载 RK3568 ARM64 交叉编译环境"
echo "========================================"

if [ ! -f "$SDK_ENV" ]; then

    echo
    echo "[错误] 找不到 SDK 环境："
    echo "$SDK_ENV"

    error_exit "SDK 环境"

fi

source "$SDK_ENV"

echo
echo "CROSS_COMPILE = $CROSS_COMPILE"
echo "ARCH           = $ARCH"


# =========================================================
# 检查交叉编译器
# =========================================================

echo
echo "检查 C++ 交叉编译器："

if ! command -v aarch64-buildroot-linux-gnu-g++ >/dev/null 2>&1; then

    echo
    echo "[错误] 找不到 ARM64 C++ 交叉编译器"

    error_exit "交叉编译器"

fi

echo
echo "C++ 编译器："
which aarch64-buildroot-linux-gnu-g++

echo
echo "编译器版本："
aarch64-buildroot-linux-gnu-g++ --version | head -n 1


# =========================================================
# [2/7] 检查项目
# =========================================================

echo
echo "========================================"
echo "[2/7] 检查 Qt 项目"
echo "========================================"

echo
echo "项目目录："
echo "$PROJECT"

if [ ! -d "$PROJECT" ]; then

    echo
    echo "[错误] 项目目录不存在！"

    error_exit "项目目录"

fi

cd "$PROJECT"


# =========================================================
# 查找 .pro 文件
# =========================================================

PRO_FILES=( *.pro )

if [ ! -f "${PRO_FILES[0]}" ]; then

    echo
    echo "[错误] 当前目录没有找到 .pro 文件！"

    echo
    echo "当前目录："
    pwd

    echo
    echo "目录内容："
    ls -lh

    error_exit ".pro 文件"

fi

PRO_FILE="${PRO_FILES[0]}"

echo
echo "Qt 项目文件："
echo "$PRO_FILE"


# =========================================================
# [3/7] 清理旧编译
# =========================================================

echo
echo "========================================"
echo "[3/7] 清理上一次编译"
echo "========================================"

if [ -f Makefile ]; then

    echo
    echo "执行：make clean"

    make clean || true

fi


# 删除 qmake 生成文件
rm -f Makefile
rm -f .qmake.stash
rm -f .qmake.cache

echo
echo "旧编译文件清理完成"


# =========================================================
# [4/7] 检查 qmake
# =========================================================

echo
echo "========================================"
echo "[4/7] 检查 qmake"
echo "========================================"

if ! command -v qmake >/dev/null 2>&1; then

    echo
    echo "[错误] 找不到 qmake"

